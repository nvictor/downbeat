func readsGUSLikeTheDiary(text: String, signature: String, hits: [Int]) throws {
    let gus = try GUS(text)
    #expect(gus.meter.description == signature)
    #expect(gus.hits == hits)
}

@Test(arguments: [
    "A↓", "P7", "P4 X(1)", "P4 N(1)", "P4 O(1)<", "P8 U(1)", "P16 N(1)<", "P4 O(5)", "P4 O(1) S(1)<",
    "5/8 · P4 A↓",
])
func refusesBadGUS(text: String) {
    #expect(throws: LayoutError.self) { try GUS(text) }
}

@Test func takesTheMeterOfTheBar() throws {
    #expect(try GUS("P6", meter: Meter("6/8")).steps.count == 12)
    #expect(try GUS("P6", meter: Meter("6/8")).meter.description == "6/8")
    #expect(throws: LayoutError.self) { try GUS("3/4 · P6", meter: Meter("4/4")) }
}

@Test func readsPAL() throws {
    let song = try PAL("6/8 · 69 bpm · A4 (B8 C8)x2 A4")
    #expect(song.meter == Meter("6/8"))
    #expect(song.tempo == 69)
    #expect(song.parts.map(\.id) == ["A", "B", "C", "B", "C", "A"])
    #expect(song.distinct.map(\.bars) == [4, 8, 8])
    #expect(try PAL("A8 B16 C16 B'16 C16 D8").distinct.map(\.id) == ["A", "B", "C", "B'", "D"])
    #expect(try PAL("A4x4").parts.count == 4)
}

